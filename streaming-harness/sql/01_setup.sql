-- IDP demo: Snowflake objects for the streaming harness (already applied to SFSEEUROPE-EU_DEMO59)
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS IDP_DEMO;
CREATE SCHEMA IF NOT EXISTS IDP_DEMO.STREAMING;

-- Append-only interactive table (CDC version: see 02_cdc_table.sql)
CREATE OR REPLACE INTERACTIVE TABLE IDP_DEMO.STREAMING.PRODUCT_PAYLOAD (
  PRODUCT_ID          VARCHAR(20),
  PRODUCT_VERSION     NUMBER(18,0),
  EVENT_TYPE          VARCHAR(10),      -- CREATE / UPDATE / DELETE (soft)
  EVENT_TS            TIMESTAMP_NTZ(6),
  SOURCE_SYSTEM       VARCHAR(30),
  ISIN                VARCHAR(12),
  CUSIP               VARCHAR(9),
  SEDOL               VARCHAR(7),
  FIGI                VARCHAR(12),
  TICKER              VARCHAR(20),
  MIC                 VARCHAR(4),
  PRODUCT_NAME        VARCHAR(200),
  ASSET_CLASS         VARCHAR(20),
  ASSET_SUBCLASS      VARCHAR(40),
  CFI_CODE            VARCHAR(6),
  ISSUER_NAME         VARCHAR(200),
  ISSUER_LEI          VARCHAR(20),
  COUNTRY_OF_ISSUE    VARCHAR(2),
  CURRENCY            VARCHAR(3),
  COUPON_RATE         NUMBER(9,6),
  ISSUE_DATE          DATE,
  MATURITY_DATE       DATE,
  PRICE               NUMBER(18,6),
  PRICE_TS            TIMESTAMP_NTZ(6),
  PLACE_OF_SETTLEMENT VARCHAR(20),
  SETTLEMENT_CYCLE    VARCHAR(5),
  CA_PENDING          BOOLEAN,
  CA_EVENT_TYPE       VARCHAR(20),
  STATUS              VARCHAR(12),
  PAYLOAD             VARIANT           -- full nested UDM message
)
CLUSTER BY (PRODUCT_ID);

CREATE OR REPLACE PIPE IDP_DEMO.STREAMING.PRODUCT_PAYLOAD_PIPE
  AS COPY INTO IDP_DEMO.STREAMING.PRODUCT_PAYLOAD
  FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Interactive warehouse for serving lookups (24 h minimum auto-suspend: suspend when not demoing)
CREATE INTERACTIVE WAREHOUSE IF NOT EXISTS IDP_IW_XS
  TABLES (IDP_DEMO.STREAMING.PRODUCT_PAYLOAD)
  WAREHOUSE_SIZE = 'XSMALL';
ALTER WAREHOUSE IDP_IW_XS SUSPEND;

CREATE WAREHOUSE IF NOT EXISTS IDP_ADMIN_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;

-- Streaming service user (key-pair auth)
CREATE ROLE IF NOT EXISTS IDP_STREAMING_RL;
CREATE USER IF NOT EXISTS IDP_STREAMING_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = IDP_STREAMING_RL
  RSA_PUBLIC_KEY = '<contents of keys/rsa_key.pub without header/footer>';

GRANT USAGE ON DATABASE IDP_DEMO TO ROLE IDP_STREAMING_RL;
GRANT USAGE ON SCHEMA IDP_DEMO.STREAMING TO ROLE IDP_STREAMING_RL;
GRANT INSERT, SELECT ON TABLE IDP_DEMO.STREAMING.PRODUCT_PAYLOAD TO ROLE IDP_STREAMING_RL;
GRANT OPERATE, MONITOR ON PIPE IDP_DEMO.STREAMING.PRODUCT_PAYLOAD_PIPE TO ROLE IDP_STREAMING_RL;
GRANT ROLE IDP_STREAMING_RL TO USER IDP_STREAMING_SVC;
GRANT ROLE IDP_STREAMING_RL TO ROLE SYSADMIN;
